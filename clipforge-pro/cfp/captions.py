"""Stage 6 - word-level ASS subtitles with an animated active word.

Captions are emitted 1-3 words at a time. For each word in a group we write
one Dialogue line covering that word's own timing, rendering the whole group
with the current word recoloured and briefly scaled up. Played back, the group
sits still while the highlight steps through it.

Two format rules that cause silent, confusing breakage if changed:

* The ``[Events] Format:`` line must list all **ten** fields (Layer, Start,
  End, Style, Name, MarginL, MarginR, MarginV, Effect, Text). A short format
  line makes libass misparse every row that follows and leak text.
* ``{`` and ``}`` open and close override blocks, so any brace in the spoken
  text must be replaced before it reaches the file.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass

from .config import TARGET_H, TARGET_W, CaptionStyle
from .models import Word

log = logging.getLogger("cfp.captions")

# Every field libass expects, in order. Do not shorten.
EVENT_FORMAT = (
    "Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
)
STYLE_FORMAT = (
    "Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
    "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, "
    "Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, "
    "MarginV, Encoding"
)

MAX_GAP_HOLD = 0.30     # hold a word on screen across gaps shorter than this
MIN_WORD_SHOW = 0.12


def ass_time(seconds: float) -> str:
    """ASS wants H:MM:SS.cc -- centiseconds, single-digit hour."""
    seconds = max(0.0, seconds)
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    whole = int(seconds % 60)
    centis = int(round((seconds - int(seconds)) * 100))
    if centis == 100:                      # rounding pushed us to the next second
        centis = 0
        whole += 1
        if whole == 60:
            whole = 0
            minutes += 1
            if minutes == 60:
                minutes = 0
                hours += 1
    return f"{hours}:{minutes:02d}:{whole:02d}.{centis:02d}"


def escape_text(text: str) -> str:
    """Make arbitrary spoken text safe for the ASS Text field."""
    out = text.replace("\\", "/").replace("{", "(").replace("}", ")")
    out = out.replace("\r", " ").replace("\n", " ")
    return re.sub(r"\s+", " ", out).strip()


def inline_colour(style_colour: str) -> str:
    """``&HAABBGGRR`` (style form) -> ``&HBBGGRR&`` (override-tag form)."""
    raw = style_colour.strip().lstrip("&").lstrip("Hh").rstrip("&")
    if len(raw) >= 8:
        raw = raw[-6:]                      # drop the alpha byte
    return f"&H{raw.upper()}&"


@dataclass
class CaptionGroup:
    words: list[Word]

    @property
    def start(self) -> float:
        return self.words[0].start

    @property
    def end(self) -> float:
        return self.words[-1].end


def group_words(
    words: list[Word], per_frame: int = 3, max_gap: float = 0.7
) -> list[CaptionGroup]:
    """Chunk words, breaking on sentence ends and long pauses."""
    groups: list[CaptionGroup] = []
    bucket: list[Word] = []

    def flush() -> None:
        if bucket:
            groups.append(CaptionGroup(list(bucket)))
            bucket.clear()

    for word in words:
        if bucket and (word.start - bucket[-1].end) > max_gap:
            flush()
        bucket.append(word)
        if len(bucket) >= max(1, per_frame) or re.search(r"[.!?,;:]$", word.text):
            flush()
    flush()
    return groups


def strip_punctuation(text: str) -> str:
    """Captions read better without trailing punctuation."""
    return re.sub(r"^[^\w'(\[]+|[^\w')\]]+$", "", text)


def _script_info() -> list[str]:
    return [
        "[Script Info]",
        "; Generated by ClipForge Pro",
        "ScriptType: v4.00+",
        f"PlayResX: {TARGET_W}",
        f"PlayResY: {TARGET_H}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
    ]


def _styles(style: CaptionStyle) -> list[str]:
    bold = -1 if style.bold else 0
    return [
        "[V4+ Styles]",
        f"Format: {STYLE_FORMAT}",
        (
            f"Style: Caption,{style.font},{style.size},{style.base_color},"
            f"{style.highlight_color},{style.outline_color},{style.shadow_color},"
            f"{bold},0,0,0,100,100,0,0,1,{style.outline},{style.shadow},"
            f"{style.alignment},{style.margin_h},{style.margin_h},{style.margin_v},1"
        ),
        (
            f"Style: Hook,{style.font},{style.hook_size},{style.hook_color},"
            f"{style.hook_color},{style.hook_outline_color},{style.shadow_color},"
            f"{bold},0,0,0,100,100,0,0,1,{style.outline},{style.shadow},"
            f"{style.hook_alignment},{style.margin_h},{style.margin_h},"
            f"{style.hook_margin_v},1"
        ),
        "",
    ]


def _dialogue(start: float, end: float, text: str, style_name: str = "Caption") -> str:
    # Ten fields, matching EVENT_FORMAT exactly.
    return (
        f"Dialogue: 0,{ass_time(start)},{ass_time(end)},{style_name},,0,0,0,,{text}"
    )


def render_group(group: CaptionGroup, active: int, style: CaptionStyle) -> str:
    """The group's text with word ``active`` highlighted and popped."""
    highlight = inline_colour(style.highlight_color)
    base = inline_colour(style.base_color)
    pieces: list[str] = []

    for i, word in enumerate(group.words):
        token = strip_punctuation(word.text)
        if style.uppercase:
            token = token.upper()
        token = escape_text(token)
        if not token:
            continue
        if i == active:
            pop = (
                f"{{\\1c{highlight}\\fscx{style.pop_scale}\\fscy{style.pop_scale}"
                f"\\t(0,{style.pop_ms},\\fscx100\\fscy100)}}"
            )
            pieces.append(f"{pop}{token}{{\\1c{base}\\fscx100\\fscy100}}")
        else:
            pieces.append(token)
    return " ".join(pieces)


def build_ass(
    words: list[Word],
    *,
    style: CaptionStyle,
    clip_start: float = 0.0,
    clip_end: float | None = None,
    hook: str = "",
) -> str:
    """Render an ASS subtitle file for one clip.

    ``words`` carry **source** timestamps; ``clip_start`` is subtracted so the
    output is relative to the trimmed clip.
    """
    span = (clip_end - clip_start) if clip_end is not None else None
    local: list[Word] = []
    for word in words:
        start = word.start - clip_start
        end = word.end - clip_start
        if span is not None:
            if end <= 0 or start >= span:
                continue
            start = max(0.0, start)
            end = min(span, end)
        if end - start < 0.01:
            continue
        local.append(Word(start, end, word.text))

    lines = _script_info() + _styles(style)
    lines += ["[Events]", f"Format: {EVENT_FORMAT}"]

    if hook:
        hook_text = escape_text(hook.upper() if style.uppercase else hook)
        hook_end = style.hook_seconds if span is None else min(style.hook_seconds, span)
        if hook_text and hook_end > 0:
            lines.append(_dialogue(0.0, hook_end, hook_text, "Hook"))

    groups = group_words(local, per_frame=style.words_per_frame)
    for group in groups:
        for i, word in enumerate(group.words):
            start = word.start
            end = max(word.end, start + MIN_WORD_SHOW)
            # Hold across a short gap so the group does not flicker.
            if i + 1 < len(group.words):
                nxt = group.words[i + 1].start
                if 0 < nxt - word.end <= MAX_GAP_HOLD:
                    end = nxt
            else:
                end = min(end, group.end + MAX_GAP_HOLD)
            if span is not None:
                end = min(end, span)
            if end <= start:
                continue
            text = render_group(group, i, style)
            if text:
                lines.append(_dialogue(start, end, text))

    return "\n".join(lines) + "\n"


def write_ass(path: str, content: str) -> str:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    return path
